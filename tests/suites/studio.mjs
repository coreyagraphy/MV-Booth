import { chromium } from "playwright-core";
const S = process.cwd();
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined });
const p = await b.newPage({ viewport: { width: 1600, height: 960 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.stack)); p.on("console", (m) => m.type() === "error" && !/Failed to load resource/.test(m.text()) && errs.push(m.text()));
const B = (fn, a) => p.evaluate(fn, a);
const ok = (n, c, x = "") => console.log(`${c ? "PASS" : "FAIL"} ${n} ${x}`);
await p.goto(process.env.BASE_URL); await p.waitForTimeout(1200);
await p.setInputFiles("#fileVocal", `${S}/vocal.wav`); await p.waitForFunction(() => window.__booth.session.tracks.length === 1);
const before = await B(() => { const t = window.__booth.session.tracks[0]; const d = window.__booth.audio.get(t.takes[0].id).getChannelData(0); let h = 0; for (let i = 0; i < d.length; i += 97) h = (h * 31 + Math.round(d[i] * 1e6)) | 0; return { id: t.takes[0].id, h, len: d.length }; });
await p.click('.tabs button[data-tab="tune"]'); await p.waitForTimeout(1500);
ok("backend online in UI", (await p.getAttribute("#beDot", "class")).includes("ok"), await p.textContent("#beStatus"));
await p.click("#btnStudioTune");
await p.waitForFunction(() => window.__booth.session.tracks[0].takes.length === 2, null, { timeout: 180000 });
const after = await B(() => { const t = window.__booth.session.tracks[0]; const d = window.__booth.audio.get(t.takes[0].id).getChannelData(0); let h = 0; for (let i = 0; i < d.length; i += 97) h = (h * 31 + Math.round(d[i] * 1e6)) | 0; return { names: t.takes.map((k) => k.name), clipTake: t.clips.map((c) => t.takes.findIndex((k) => k.id === c.takeId)), h, len: d.length, tunedLen: window.__booth.audio.get(t.takes[1].id).length, rep: t.takes[1].report.summary, key: t.takes[1].report.key.label }; });
ok("tuned take added to lane", after.names[1].endsWith("· tuned"), JSON.stringify(after.names));
ok("clip swapped to tuned take", after.clipTake.every((i) => i === 1));
ok("original take untouched (bit-identical)", after.h === before.h && after.len === before.len);
ok("tuned length matches", Math.abs(after.tunedLen - after.len) < 2, `${after.tunedLen} vs ${after.len}`);
ok("region report", after.rep.regions > 0, `${after.key} · ${JSON.stringify(after.rep)}`);
ok("report panel", (await p.locator("#studioReport .rg").count()) === after.rep.regions);
await p.keyboard.press("Control+z");
ok("undo restores original on track", (await B(() => { const t = window.__booth.session.tracks[0]; return t.takes.length === 1 && t.clips[0].takeId === t.takes[0].id; })));
await p.keyboard.press("Control+Shift+z");
await p.click('.tabs button[data-tab="booth"]');
await p.screenshot({ path: `${S}/studio.png` });
await p.click('.tabs button[data-tab="tune"]'); await p.waitForTimeout(400);
await p.screenshot({ path: `${S}/studio-tab.png`, clip: { x: 1210, y: 250, width: 390, height: 700 } });
console.log("errors", errs);
await b.close();
