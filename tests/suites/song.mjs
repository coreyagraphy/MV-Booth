import { chromium } from "playwright-core";
const S = process.cwd();
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined,
  args: ["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream", `--use-file-for-fake-audio-capture=${S}/vocal.wav`, "--autoplay-policy=no-user-gesture-required"] });
const p = await b.newPage({ viewport: { width: 1600, height: 960 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.stack)); p.on("console", (m) => m.type() === "error" && !/Failed to load resource/.test(m.text()) && errs.push(m.text()));
const B = (fn, a) => p.evaluate(fn, a);
const ok = (n, c, x = "") => console.log(`${c ? "PASS" : "FAIL"} ${n} ${x}`);
await p.goto(process.env.BASE_URL); await p.waitForTimeout(1200);
// Song tab
await p.click('.tabs button[data-tab="song"]');
let steps = await p.$$eval("#songSteps li", (l) => l.map((x) => x.className + "|" + x.querySelector("b").textContent));
ok("song checklist has 10 steps, beat is next", steps.length === 10 && /next/.test(steps[0]), JSON.stringify(steps.slice(0, 2)));
await p.setInputFiles("#fileBeat", `${S}/beat.wav`); await p.waitForFunction(() => window.__booth.session.beats.length);
await p.setInputFiles("#fileVocal", `${S}/vocal.wav`); await p.waitForFunction(() => window.__booth.session.tracks.length === 1);
await p.click('.tabs button[data-tab="song"]');
await p.locator("#songSteps button", { hasText: "Intro" }).click();
await B(() => window.__booth.seek(8));
await p.locator("#songSteps button", { hasText: "Verse" }).click();
ok("section markers added", await B(() => window.__booth.session.markers.map((m) => m.name).join(",")) === "Intro,Verse");
steps = await p.$$eval("#songSteps li", (l) => l.map((x) => x.className + "|" + x.querySelector("b").textContent));
ok("beat/record done, Clean is next", /done/.test(steps[0]) && /done/.test(steps[2]) && /next/.test(steps[4]), steps.filter((s) => /next/.test(s)).join());
await p.screenshot({ path: `${S}/song.png` });
// Clean tab
await B(() => { const t = window.__booth.session.tracks[0]; window.__booth.ui.selTrack = t.id; });
await p.click('.tabs button[data-tab="clean"]');
await p.locator("#clDenoise").fill("0.8");
await p.locator('#clBreaths button[data-v="remove"]').click();
await p.locator("#clDeess").fill("0.9");
await p.locator('#clHum button[data-v="60"]').click();
const cl = await B(() => window.__booth.session.tracks[0].clean);
ok("clean settings stored on track", cl && cl.denoise === 0.8 && cl.breaths === "remove" && cl.deess === 0.9 && cl.hum === "60" && cl.pop === true, JSON.stringify(cl));
const rawId = await B(() => window.__booth.session.tracks[0].takes[0].id);
const sum0 = await B((id) => { const d = window.__booth.audio.get(id).getChannelData(0); let s = 0; for (let i = 0; i < d.length; i++) s += d[i] * (i % 97); return s; }, rawId);
await p.click("#btnCleanPreview");
await p.waitForFunction(() => window.__booth.session.tracks[0].takes.length === 2, null, { timeout: 60000 });
const tk = await B(() => { const t = window.__booth.session.tracks[0]; return { names: t.takes.map((k) => k.name), clip: t.clips.map((c) => c.takeId), id1: t.takes[1].id, rep: t.takes[1].cleanReport }; });
ok("cleaned take added + clips swapped", /· clean$/.test(tk.names[1]) && tk.clip.every((c) => c === tk.id1), JSON.stringify(tk.names));
const sum1 = await B((id) => { const d = window.__booth.audio.get(id).getChannelData(0); let s = 0; for (let i = 0; i < d.length; i++) s += d[i] * (i % 97); return s; }, rawId);
ok("raw take untouched", sum0 === sum1);
const rep = await p.innerText("#cleanReport");
ok("clean report shows breaths / pop / de-click / hum", /Breath/i.test(rep) && /Pop/i.test(rep) && /click/i.test(rep) && /Hum/i.test(rep), rep.replace(/\n/g, " | ").slice(0, 400));
await p.screenshot({ path: `${S}/clean.png` });
await p.keyboard.press("Control+z");
ok("undo restores raw take on track", await B((id) => window.__booth.session.tracks[0].clips.every((c) => c.takeId === id), rawId));
await p.keyboard.press("Control+Shift+z");
// Master section
await p.click('.tabs button[data-tab="mixer"]');
await p.selectOption("#masterTone", "warm");
await p.selectOption("#ceiling", "-2");
await p.locator("#width").fill("1.2");
ok("master settings stored", await B(() => { const s = window.__booth.session.settings; return s.masterTone === "warm" && s.ceiling === -2 && Math.abs(s.width - 1.2) < 1e-6; }));
await p.click("#btnAutomix");
await p.waitForFunction(() => window.__booth.ui.master && !window.__booth.ui.stale && !document.body.classList.contains("busy"), null, { timeout: 180000 });
const notes = await p.innerText("#report");
ok("report mentions cleanup + tone/width/ceiling", /warm/i.test(notes) && /120%|width/i.test(notes) && /ceiling -2 dBTP/.test(notes), notes.replace(/\n/g, " | ").slice(0, 700));
const st = await p.textContent("#status");
const tp = parseFloat(st.match(/true peak (-?[\d.]+)/)?.[1]);
ok("master -14 LUFS, true peak <= -2 ceiling", /-1[34]\.\d LUFS/.test(st) && tp <= -2.0, st);
ok("no page errors", errs.length === 0, errs.join("\n"));
await b.close();
