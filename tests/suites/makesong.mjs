// Make my song: one click → Automix → WAV + MP3 in Downloads. Also the header stays one row.
import { chromium } from "playwright-core";
import { readFileSync } from "node:fs";
const S = process.cwd();
const ok = (n, c, x = "") => console.log(`${c ? "PASS" : "FAIL"} ${n} ${x}`);
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, args: ["--autoplay-policy=no-user-gesture-required"] });
const ctx = await b.newContext({ acceptDownloads: true, viewport: { width: 1600, height: 960 } });
const p = await ctx.newPage();
const errs = []; p.on("pageerror", (e) => errs.push(e.stack)); p.on("console", (m) => m.type() === "error" && !/Failed to load resource/.test(m.text()) && errs.push(m.text()));
const B = (fn, a) => p.evaluate(fn, a);
await p.goto(process.env.BASE_URL); await p.waitForTimeout(1200);
await p.click("#btnMakeSong"); await p.waitForTimeout(300);
ok("with nothing recorded it explains instead of running", /Record or import a vocal first/.test(await p.textContent("#toast")), await p.textContent("#toast"));
await p.setInputFiles("#fileBeat", `${S}/beat.wav`); await p.waitForFunction(() => window.__booth.session.beats.length === 1);
await p.setInputFiles("#fileVocal", `${S}/vocal.wav`); await p.waitForFunction(() => window.__booth.session.tracks.length === 1);
const files = [], saves = [];
p.on("download", (d) => { const f = `${S}/make_${d.suggestedFilename()}`; files.push(f); saves.push(d.saveAs(f)); });
await p.click('.tabs button[data-tab="song"]');
await p.click("#btnMakeSongTab");
await p.waitForFunction(() => document.querySelector("#btnMakeSong").classList.contains("working"));
ok("button shows it is working", await B(() => document.querySelector("#btnMakeSong").disabled));
await p.waitForFunction(() => !document.querySelector("#btnMakeSong").classList.contains("working"), null, { timeout: 300000 });
for (let i = 0; i < 100 && files.length < 2; i++) await p.waitForTimeout(100);
await Promise.all(saves);
const wav = files.find((f) => /\.wav$/.test(f)), mp3 = files.find((f) => /\.mp3$/.test(f));
ok("one click produced the mix", await B(() => !!window.__booth.ui.master && !window.__booth.ui.stale));
ok("…and saved the master WAV", !!wav && readFileSync(wav).length > 100000, wav && `${(readFileSync(wav).length / 1048576).toFixed(1)} MB`);
ok("…and the MP3", !!mp3 && readFileSync(mp3)[0] === 0xff, mp3 && `${(readFileSync(mp3).length / 1024).toFixed(0)} KB`);
ok("status tells you what happened next", /Your song is done/.test(await p.textContent("#status")), (await p.textContent("#status")).slice(0, 80));
ok("Song checklist: Mix, Master and Export ticked", (await p.$$eval("#songSteps li.done b", (l) => l.map((x) => x.textContent))).filter((t) => /^(Mix|Master|Export)/.test(t)).length === 3);
const hdr = await B(() => Math.round(document.querySelector("header").getBoundingClientRect().height));
ok("header still one row at 1600 px with the new button", hdr <= 80, `${hdr} px`);
await p.screenshot({ path: `${S}/makesong.png` });
ok("no page errors", errs.length === 0, errs.join("\n"));
await b.close();
