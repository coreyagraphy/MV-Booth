// Make my song: one click → Automix → WAV + MP3 in Downloads. Also the header stays one row.
import { chromium } from "playwright-core";
import { readFileSync } from "node:fs";
const S = process.cwd();
const ok = (n, c, x = "") => console.log(`${c ? "PASS" : "FAIL"} ${n} ${x}`);
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, args: ["--autoplay-policy=no-user-gesture-required"] });
const ctx = await b.newContext({ acceptDownloads: true, viewport: { width: 1600, height: 960 } });
const p = await ctx.newPage();
const errs = []; p.on("pageerror", (e) => errs.push(e.stack)); p.on("console", (m) => m.type() === "error" && !/Failed to load resource/.test(m.text()) && errs.push(m.text()));
const B = (fn, a) => p.evaluate(fn, a);
await p.goto(process.env.BASE_URL); await p.waitForTimeout(1200);
await p.click("#btnMakeSong"); await p.waitForTimeout(300);
ok("with nothing recorded it explains instead of running", /Record or import a vocal first/.test(await p.textContent("#toast")), await p.textContent("#toast"));
await p.setInputFiles("#fileBeat", `${S}/beat.wav`); await p.waitForFunction(() => window.__booth.session.beats.length === 1);
await p.setInputFiles("#fileVocal", `${S}/vocal.wav`); await p.waitForFunction(() => window.__booth.session.tracks.length === 1);
const files = [], saves = [];
p.on("download", (d) => { const f = `${S}/make_${d.suggestedFilename()}`; files.push(f); saves.push(d.saveAs(f)); });
await p.click('.tabs button[data-tab="song"]');
await p.click("#btnMakeSongTab");
await p.waitForFunction(() => document.querySelector("#btnMakeSong").classList.contains("working"));
ok("button shows it is working", await B(() => document.querySelector("#btnMakeSong").disabled));
await p.waitForFunction(() => !document.querySelector("#btnMakeSong").classList.contains("working"), null, { timeout: 300000 });
ok("one click produced the mix", await B(() => !!window.__booth.ui.master && !window.__booth.ui.stale));
ok("nothing downloads before you've listened", files.length === 0 && (await B(() => !document.querySelector("#songBar").hidden)), await p.textContent("#songBarInfo"));
await p.click("#btnSongPlay"); await p.waitForTimeout(600);
ok("▶ Listen plays the mix from the top", await B(() => !!window.__booth.ui.playing && window.__booth.ui.ab === "B" && window.__booth.ui.playing.from === 0));
await p.click("#btnSongPlay"); await p.waitForTimeout(200);
ok("…and pressing it again pauses", await B(() => !window.__booth.ui.playing));
await p.click("#btnSongSave");
for (let i = 0; i < 100 && files.length < 2; i++) await p.waitForTimeout(100);
await Promise.all(saves);
const wav = files.find((f) => /\.wav$/.test(f)), mp3 = files.find((f) => /\.mp3$/.test(f));
ok("Save WAV + MP3 saves the master WAV", !!wav && readFileSync(wav).length > 100000, wav && `${(readFileSync(wav).length / 1048576).toFixed(1)} MB`);
ok("…and the MP3", !!mp3 && readFileSync(mp3)[0] === 0xff, mp3 && `${(readFileSync(mp3).length / 1024).toFixed(0)} KB`);
ok("the bar closes after saving", await B(() => document.querySelector("#songBar").hidden));
ok("status confirms the save", /Saved: WAV \+ MP3/.test(await p.textContent("#status")), (await p.textContent("#status")).slice(0, 80));
ok("Song checklist: Mix, Master and Export ticked", (await p.$$eval("#songSteps li.done b", (l) => l.map((x) => x.textContent))).filter((t) => /^(Mix|Master|Export)/.test(t)).length === 3);
const hdr = await B(() => Math.round(document.querySelector("header").getBoundingClientRect().height));
ok("header still one row at 1600 px with the new button", hdr <= 80, `${hdr} px`);
await p.screenshot({ path: `${S}/makesong.png` });
// A single recorded double is audible: centred, ~4.5 dB under the lead (not 7 dB down and off to one side).
await B(() => (window.__booth.ui.selTrack = null));
await p.setInputFiles("#fileVocal", `${S}/double.wav`); await p.waitForFunction(() => window.__booth.session.tracks.length === 2);
await B(() => { window.__booth.session.tracks[1].type = "double"; window.__booth.session.tracks[1].name = "Double 1"; });
await p.click("#btnAutomix");
await p.waitForFunction(() => window.__booth.ui.master && !window.__booth.ui.stale && !document.body.classList.contains("busy"), null, { timeout: 300000 });
const dbl = await B(async () => {
  const E = await import("./js/engine.js"); const D = await import("./js/dsp.js");
  const run = window.__booth.ui.run, s = window.__booth.session, fs = window.__booth.ctx.sampleRate;
  const lufs = async (id) => { const b = (await E.renderStem(run, { beats: [], fs, mode: s.mode, settings: { ...s.settings, stages: { ...s.settings.stages, space: false } } }, id)).buffer; return { lufs: D.integratedLoudness([b.getChannelData(0), b.getChannelData(1)], fs), bal: (() => { let l = 0, r = 0; const L = b.getChannelData(0), R = b.getChannelData(1); for (let i = 0; i < L.length; i += 7) { l += L[i] * L[i]; r += R[i] * R[i]; } return 10 * Math.log10(l / r); })() }; };
  const lead = await lufs(s.tracks[0].id), d = await lufs(s.tracks[1].id);
  return { under: lead.lufs - d.lufs, lrDb: d.bal, note: run.mix.notes.find((n) => /^Double 1/.test(n)) };
});
ok("single double sits ~4.5 dB under the lead", dbl.under > 3 && dbl.under < 6.5, `${dbl.under.toFixed(1)} dB under`);
ok("…centred, not off to one side", Math.abs(dbl.lrDb) < 0.5, `L/R ${dbl.lrDb.toFixed(2)} dB · ${dbl.note}`);
ok("no page errors", errs.length === 0, errs.join("\n"));
await b.close();
